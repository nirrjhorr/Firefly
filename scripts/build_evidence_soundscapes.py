def main():
    target_dir = os.path.join("assets", "audio")
    staging_dir = os.path.join("assets", "audio_staging")
    os.makedirs(target_dir, exist_ok=True)
    os.makedirs(staging_dir, exist_ok=True)

    print(f"Starting Evidence-Informed Audio Pipeline for {len(CANDIDATE_SOUNDS)} candidate tracks...")
    
    catalogue = []
    attributions = []

    for item in CANDIDATE_SOUNDS:
        track_id = item["id"]
        target_name = item["target_file"]
        target_path = os.path.join(target_dir, target_name)
        fmt = item["format"]
        source_url = item["source_url"]

        # 1. Download if not already present or if conversion needed
        if fmt == "wav_to_mp3":
            raw_wav = os.path.join(staging_dir, f"{track_id}.wav")
            if not os.path.exists(target_path):
                print(f"[FETCH] Downloading WAV: {track_id}...")
                req = urllib.request.Request(source_url, headers={"User-Agent": "Firefly-Audio-Research/1.0"})
                with urllib.request.urlopen(req) as resp:
                    with open(raw_wav, "wb") as f:
                        f.write(resp.read())
                
                # Convert to high-quality 192k MP3 with 2s loop-friendly crossfade or normalization
                print(f"[ENCODE] Converting {raw_wav} -> {target_path} (192kbps MP3)...")
                cmd = [
                    "ffmpeg", "-y", "-i", raw_wav,
                    "-codec:a", "libmp3lame", "-b:a", "192k",
                    "-af", "loudnorm=I=-18:TP=-1.5:LRA=11",
                    target_path
                ]
                subprocess.run(cmd, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL, check=True)
        else:
            if not os.path.exists(target_path) or os.path.getsize(target_path) < 10000:
                print(f"[FETCH] Downloading MP3: {target_name}...")
                req = urllib.request.Request(source_url, headers={"User-Agent": "Firefly-Audio-Research/1.0"})
                with urllib.request.urlopen(req) as resp:
                    with open(target_path, "wb") as f:
                        f.write(resp.read())

        # 2. Extract technical metrics via ffprobe
        file_size = os.path.getsize(target_path)
        sha256 = ""
        with open(target_path, "rb") as f:
            sha256 = hashlib.sha256(f.read()).hexdigest()

        duration = 0.0
        sample_rate = 44100
        channels = 2
        bitrate = 192000

        try:
            probe_cmd = [
                "ffprobe", "-v", "error", "-show_entries",
                "format=duration,bit_rate:stream=sample_rate,channels",
                "-of", "json", target_path
            ]
            res = subprocess.run(probe_cmd, stdout=subprocess.PIPE, stderr=subprocess.DEVNULL, text=True, check=True)
            probe_data = json.loads(res.stdout)
            format_info = probe_data.get("format", {})
            streams_info = probe_data.get("streams", [{}])[0]
            duration = round(float(format_info.get("duration", 0)), 2)
            bitrate = int(format_info.get("bit_rate", 192000))
            sample_rate = int(streams_info.get("sample_rate", 44100))
            channels = int(streams_info.get("channels", 2))
        except Exception as e:
            print(f"[WARN] Probe error for {target_name}: {e}")

        # 3. Assemble metadata
        track_meta = {
            "id": track_id,
            "title": item["title"],
            "category": item["category"],
            "subcategory": item["subcategory"],
            "description": item["description"],
            "durationSeconds": duration,
            "assetPath": f"assets/audio/{target_name}",
            "fileSizeBytes": file_size,
            "sha256": sha256,
            "format": "audio/mpeg",
            "sampleRate": sample_rate,
            "channels": channels,
            "bitrate": bitrate,
            "loopable": item["loopable"],
            "recommendedVolume": item["recommendedVolume"],
            "evidenceCategory": item["evidenceCategory"],
            "evidenceNotes": item["evidenceNotes"],
            "qualityScore": item["qualityScore"],
            "mood": item["mood"],
            "environment": item["environment"],
            "tags": item["tags"],
            "useCases": item["useCases"],
            "license": item["license"],
            "source": item["source"],
            "creator": item["creator"],
            "attribution": item["attribution"],
        }
        catalogue.append(track_meta)

        attributions.append(f"""### {item['title']} (`{target_name}`)
- **Creator / Field Recordist:** {item['creator']}
- **Source Repository:** [{item['source']}]({item['source_url']})
- **Licence:** {item['license']}
- **Integrity (SHA-256):** `{sha256}`
- **Technical Specs:** {duration}s | {sample_rate}Hz | {channels} channels | {bitrate // 1000}kbps
- **Attribution Notice:** {item['attribution']}
""")
        print(f"[OK] {item['title']:<26} | {duration:>6.1f}s | {file_size/1024/1024:>4.2f}MB | Score: {item['qualityScore']}")

    # 4. Save Audio Catalogue JSON
    catalogue_path = os.path.join(target_dir, "audio_catalogue.json")
    with open(catalogue_path, "w", encoding="utf-8") as f:
        json.dump({
            "version": "1.0.0",
            "lastUpdated": "2026-10-05",
            "totalTracks": len(catalogue),
            "totalDurationSeconds": sum(t["durationSeconds"] for t in catalogue),
            "totalSizeBytes": sum(t["fileSizeBytes"] for t in catalogue),
            "tracks": catalogue
        }, f, indent=2)
    print(f"\nWrote machine-readable catalogue to {catalogue_path}")

    # 5. Save ATTRIBUTIONS.md
    attrib_path = os.path.join(target_dir, "ATTRIBUTIONS.md")
    with open(attrib_path, "w", encoding="utf-8") as f:
        f.write("# Firefly Offline Relaxation Audio: Third-Party Licences & Attributions\n\n")
        f.write("All audio assets bundled into Firefly are strictly verified for 100% offline, privacy-critical local distribution with perpetual commercial and redistribution rights.\n\n")
        f.write("\n".join(attributions))
    print(f"Wrote attributions file to {attrib_path}")

if __name__ == "__main__":
    main()
